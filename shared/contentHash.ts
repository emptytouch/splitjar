import type { Hex } from 'viem'

/**
 * 链上 `Content.contentHash` 那一格的**零值**,以及"它能不能用来核对"这一条判断。
 *
 * ## 为什么它需要单独一个文件
 *
 * 有两处要知道这件事:看板取行的时候要把"事件里没带"补成零值
 * (`hooks/useMyContents.ts`),补预览图的时候要判"这一份到底核对得了吗"
 * (`lib/backfillMachine.ts`)。**照抄一份到第二处就是两份会漂移的判断** ——
 * 这个仓库对这种事的处理一直是"抽出来共用",不是"记得同步"。
 *
 * ## 零值是什么意思:一个**诚实的历史遗留**
 *
 * W5 打通上传之前,`createContent` 的 `contentHash` 实参传的是占位符 `0x0`
 * (那时代码里明确写着"上传还没做")。合约不禁止它 —— 它是一个合法的 bytes32。
 * 所以**在部署的合约上真的可能存在 `contentHash == 0x00…00` 的内容**。
 *
 * 那种内容**核对不了**:手里没有任何东西能证明"你选的这个文件就是它"。
 *
 * ## 核对不了时**不拦**,但必须说出来
 *
 * 补预览图这条路上,零值意味着"指纹比对这一步做不了"。两种处理:
 *
 * - **拦住** —— 代价是那些内容永远补不上预览图,而它们恰恰是最早的那批。
 * - **放行 + 明说** —— 代价是创作者**可以**给这一类内容配一张对不上的图。
 *
 * 选了后者,因为那个代价是**他自己的**:图挂在他自己的商品上,受害的是
 * 他自己的买家口碑,而且它不会让任何人拿到付费内容(预览图是派生图,
 * 公开 store 里本来就只有缩略图,见 `lib/previewDerive.ts` 文件头)。
 * 但界面上必须**明说"我们没法核对"**,不能让创作者以为这张图被验过。
 */
export const ZERO_CONTENT_HASH: Hex = `0x${'0'.repeat(64)}`

/**
 * 这个链上指纹**能不能**拿来核对"你选的文件就是这份内容"。
 *
 * ⚠️ 返回 `false` 不等于"内容有问题",只等于**核对这一步做不了**。
 * 调用方据此决定要不要向用户交代一句,而不是据此拒绝。
 */
export function isVerifiableHash(hash: Hex | null | undefined): hash is Hex {
  return typeof hash === 'string' && hash.toLowerCase() !== ZERO_CONTENT_HASH
}
